/**
 * What each badge is for, and what its title is referring to. The prose the
 * badge modal draws, and the answer to the user's own question: "a picture of
 * the medal, and what this badge means".
 *
 * **A peer of `badges.ts`, not a wrapper, and it is here rather than there for a
 * measured reason.** `reveal.ts` carries the note that `BADGE_CATALOG` "is a
 * pure array of strings and comes along harmlessly"; it is imported by
 * `reward-toast.tsx`, which `/today` mounts unconditionally. So anything added
 * to `badges.ts` ships to every visit of a screen that will never render it.
 * Fourteen conditions and fourteen glosses are ~4.6 kB raw — small, and
 * entirely wasted there. This module is imported by `badge-dialog.tsx` and
 * `scripts/check-gamification.ts` and by nothing else. In particular
 * `reveal.ts`, `on-card-created.ts` and `recompute.ts` must not import it.
 *
 * Browser-safe by construction: no `import "server-only"`, no zod value import,
 * no React, no clock, no database. The `BadgeKey` import is **type-only**, so it
 * adds no runtime edge and cannot create a cycle.
 *
 * **No art path here.** `BADGE_ART` in `badge-art.ts` owns that, is generated by
 * `tools/make_badge_assets.py`, and carries content-hashed filenames — a
 * hand-written path in this file would drift from the files on disk the first
 * time a badge was regenerated. F11–F18 brief [C3].
 *
 * **Register**, enforced by `npm run stats:check` rather than remembered:
 *
 *  - No second person. The app uses "you" only about its own machinery
 *    ("Pronunciation and meaning are fetched for you"), never to congratulate.
 *    Stating the rule as a fact about cards is also what lets one string serve
 *    both the earned and the unearned state, which F13 D2 requires.
 *  - No exclamation, no flattery, no loss aversion, no deadline.
 *  - Typographic apostrophes only, per the note at the top of `levels.ts`.
 *  - `condition` ≤ 140 characters, `gloss` ≤ 320.
 */

export type BadgeMeta = {
  /** The rule. One sentence, present tense, impersonal. */
  condition: string;
  /** What the title refers to, and why the day is the day. One to three sentences. */
  gloss: string;
};

