/**
 * Null for a key that is not in the catalog, mirroring `badgeTitle` exactly. The
 * two must behave the same way or the next reader will assume they do and be
 * wrong. The shelf already drops unknown keys upstream in `getProfileStats`, so
 * this is belt and braces.
 */
export function badgeMeta(key: string): BadgeMeta | null {
  return (BADGE_META as Record<string, BadgeMeta>)[key] ?? null;
}
